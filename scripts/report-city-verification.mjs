#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "docs/city-verification-inventory.md");
const context = vm.createContext({ window: {} });
for (const name of [
  "destinations", "country-guides", "city-guides", "trip-content",
  "top-100-destinations", "destination-expansion", "destination-coverage",
  "city-source-ledger"
]) {
  const file = path.join(root, "data", `${name}.js`);
  vm.runInContext(fs.readFileSync(file, "utf8"), context, { filename: file });
}
const data = context.window.HB_DATA;
const audit = JSON.parse(execFileSync(process.execPath, [
  "scripts/generate-pages.mjs", "--base=/fun-app",
  "--origin=https://hamiltondan20-sys.github.io", "--out=.",
  "--min-words=350", "--dry-run", "--audit-json"
], { cwd: root, encoding: "utf8", maxBuffer: 10 * 1024 * 1024 }));

const hasEvidence = (source) => {
  if (!source?.sourceType || !source.operatingEvidence
    || !/^\d{4}-\d{2}-\d{2}$/.test(source.checkedOn || "")) return false;
  try {
    return new URL(source.url).protocol === "https:";
  } catch {
    return false;
  }
};

const rows = audit.cities.map((city) => {
  const ledger = data.citySourceLedger?.[city.city];
  const names = [...new Set(Object.values(data.cityGuideDetailData[city.city] || {})
    .filter(Array.isArray).flat())];
  const evidenceCount = names.filter((name) => hasEvidence(ledger?.placeSources?.[name])).length;
  const complete = names.length > 0 && evidenceCount === names.length
    && ledger?.status === "source-checked"
    && ledger.reviewScope === "cityGuideDetailData"
    && ledger.verificationMethod === "official-web-review"
    && Boolean(ledger.limitations);
  // A declared review with missing records must not silently retain a verified label.
  if (ledger?.status === "source-checked" && !complete) {
    throw new Error(`${city.city}: source-checked review no longer covers every recommendation.`);
  }
  return {
    ...city,
    status: !city.eligible ? "held-back" : complete ? "source-verified" : "classifier-passed",
    evidenceCount,
    review: ledger?.status || "not-reviewed",
    populated: city.fields.filter((field) => field.named + field.descriptor + field.placeholder > 0).length
  };
}).sort((a, b) => a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0);

const counts = Object.fromEntries(["source-verified", "classifier-passed", "held-back"]
  .map((status) => [status, rows.filter((row) => row.status === status).length]));
const unmatchedKeys = Object.keys(data.cityGuideDetailData)
  .filter((key) => !rows.some((row) => row.city === key)).sort();
const escape = (value) => String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const lines = [
  "# City Verification Inventory", "",
  "Generated by `node scripts/report-city-verification.mjs`. Run with `--check` to detect stale records.", "",
  "This reports evidence already recorded by a person. It does not visit source URLs or establish that a business is open.",
  "Publication eligibility comes from the generator's read-only audit with its unchanged operating gates.", "",
  `- Canonical destination records: ${rows.length}. Raw detail records: ${Object.keys(data.cityGuideDetailData).length}.`,
  `- Source-verified (complete dated evidence format): ${counts["source-verified"]}.`,
  `- Classifier-passed (published, not fully documented in that format): ${counts["classifier-passed"]}.`,
  `- Held back: ${counts["held-back"]}.`,
  `- Published destinations: ${audit.cityCount}; country hubs: ${audit.countryCount}; sitemap URLs: ${audit.sitemapCount}.`, "",
  "Austin's prior source review is retained in the Review column. Its classifier-passed label here means the newer evidence format is incomplete, not that its earlier research was disproved.",
  "The Evidence column counts distinct current recommendations with an HTTPS source, date, source type, and operating/context evidence. Zero means no qualifying records, not zero real places in the city.",
  "Named entries include repeats across fields and are NOT verified places. Populated categories may still contain generic text.", "",
  "## Merged Source Records", "",
  "The generator merges duplicate destination records before assessing publication. Source keys without their own canonical row:",
  ...unmatchedKeys.map((key) => `- ${escape(key)}`), "",
  "Guilin and Li River, China is merged into Guilin, China by the existing generator. It is not a second held-back page.", "",
  "## All Canonical Destinations", "",
  "| Destination | Slug | Status | Review | Evidence | Named entries | Populated categories | Named categories | Hold reason |",
  "| --- | --- | --- | --- | ---: | ---: | ---: | ---: | --- |",
  ...rows.map((row) => `| ${[
    row.city, row.slug, row.status, row.review, row.evidenceCount,
    row.named, row.populated, row.categories, row.reasons.join("; ") || "None"
  ].map(escape).join(" | ")} |`), ""
];
const rendered = lines.join("\n");
if (process.argv.includes("--check")) {
  const existing = fs.existsSync(output) ? fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n") : "";
  if (existing !== rendered) throw new Error("Verification inventory is stale. Run node scripts/report-city-verification.mjs.");
  console.log(`Verification inventory is current: ${rows.length} destinations.`);
} else {
  fs.writeFileSync(output, rendered);
  console.log(`Wrote ${rows.length} destinations: ${JSON.stringify(counts)}.`);
}
